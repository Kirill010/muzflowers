class Command(BaseCommand):
    help = ('Добавляет начальные данные магазина: точки, разделы, букеты, дополнения, вопросы и ответы. '
            'Ничего не перезаписывает: если каталог уже заполнен, он остаётся как есть.')

    def handle(self, *args, **options):
        SiteSettings.load()  # настройки магазина создаются со значениями по умолчанию (телефон, часы и т. д.)

        if not Shop.objects.exists():
            Shop.objects.create(name='Выхино', address='ул. Вешняковская, 39Г',
                                map_url=SiteSettings.load().yandex_maps_url, order=1)
            self.stdout.write('Точка самовывоза: Выхино, ул. Вешняковская, 39Г')

        if not Product.objects.exists():
            cats = {slug: Category.objects.get_or_create(slug=slug, defaults={'name': name, 'description': text, 'order': order})[0]
                    for slug, name, text, order in CATEGORIES}
            for cat, name, tagline, price, kind, count, a, b, badge, ready, pop, text, s_from, s_to in PRODUCTS:
                Product.objects.create(category=cats[cat], name=name, tagline=tagline, price=price, art_kind=kind, art_count=count,
                                       color_a=a, color_b=b, badge=badge, is_ready=ready, popularity=pop, description=text,
                                       occasion=PRODUCT_OCCASIONS[name], season_from=s_from, season_to=s_to)
            self.stdout.write(self.style.SUCCESS(f'Букеты: добавлено {len(PRODUCTS)} (цены — из вашего списка, меняйте в панели)'))

        if not Addon.objects.exists():
            Addon.objects.create(name='Музыкальная открытка', price=300, is_music=True, note_required=True, order=1,
                                 description='Открытка с QR-кодом: получатель наведёт камеру — и зазвучит ваша песня',
                                 note_label='Какая песня? Название и исполнитель или ссылка')
            Addon.objects.create(name='Упаковка «В дорогу»', price=0, order=2,
                                 description='Колба с водой у стеблей и плотная упаковка — букет доедет свежим 6–12 часов')
            self.stdout.write('Дополнения: музыкальная открытка (300 ₽), упаковка «В дорогу» (бесплатно)')

        if not FAQ.objects.exists():
            FAQ.objects.bulk_create(FAQ(question=q, answer=a, order=i) for i, (q, a) in enumerate(FAQS, 1))
            self.stdout.write(f'Вопросы и ответы: {len(FAQS)}')

        if not Group.objects.filter(name=FLORIST_GROUP).exists():
            group = Group.objects.create(name=FLORIST_GROUP)
            group.permissions.set(Permission.objects.filter(content_type__app_label='shop', codename__in=FLORIST_PERMISSIONS))
            self.stdout.write(f'Группа сотрудников «{FLORIST_GROUP}» (заказы и наличие; без настроек сайта)')

        self.stdout.write(self.style.SUCCESS('Готово.'))
