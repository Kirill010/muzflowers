from .models import FAQ
from .utils import rub


def presentation_questions(site, *, storefront=False):
    payment = (
        'Флорист назовёт сумму и доступные способы оплаты при заказе по телефону.'
        if storefront else
        'Доступные способы оплаты покажем при оформлении. Предоплату можно внести онлайн или переводом, в зависимости от доступных способов.'
    )
    if site.allow_pay_on_receipt:
        payment += ' Для заказов без предоплаты доступна оплата при получении.'
    if site.prepay_future_orders:
        payment += ' Заказ на другую дату принимаем по предоплате.'

    delivery = 'Сейчас доступен самовывоз в Выхино.'
    if site.delivery_enabled:
        timing = 'Дату и время согласуем по телефону.' if storefront else 'Выберите дату и интервал при оформлении.'
        delivery = f'Доставляем по Москве. {timing} Стоимость доставки — {rub(site.delivery_cost)}.'
        if site.delivery_lead_minutes:
            delivery += f' Ближайший интервал доставки начинается не раньше чем через {site.delivery_lead_minutes} мин.'
        if site.free_delivery_from:
            delivery += f' При заказе от {rub(site.free_delivery_from)} доставка бесплатная.'
        delivery += ' Самовывоз в Выхино бесплатный.'

    return [
        FAQ(question='Сколько простоят цветы?',
            answer='Срок зависит от вида цветов и ухода. Поставьте букет в чистую прохладную воду и держите вдали от солнца и батарей. Если цветы завяли вскоре после получения, пришлите нам фото букета — разберёмся.'),
        FAQ(question='Как производится оплата?', answer=payment),
        FAQ(question='Что такое сезонные цветы?',
            answer='Это цветы, которые появляются в продаже в определённое время года. Например, весной чаще бывают тюльпаны, а на стыке весны и лета — пионы. Наличие зависит от поставки.'),
        FAQ(question='Как ухаживать за букетом?',
            answer='Подрежьте стебли на 2–3 см под углом и уберите листья, которые окажутся в воде. Меняйте воду каждый день и обновляйте срез каждые два дня. Добавляйте средство для срезанных цветов по инструкции на пакетике.'),
        FAQ(question='Как осуществляется доставка?', answer=delivery),
        FAQ(question='Почему нельзя повторить букет точь-в-точь?',
            answer='У живых цветов различаются оттенок, размер и степень раскрытия. Флорист сохранит форму и цветовую гамму букета. Если понадобится замена, согласуем её с вами.'),
    ]
